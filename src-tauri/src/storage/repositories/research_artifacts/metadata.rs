pub fn safe_request(value: &Value) -> Value {
    let mut request = value.clone();
    if let Some(map) = request.as_object_mut() {
        for key in ["features", "targets", "groups", "timestamps"] {
            map.remove(key);
        }
    }
    safe_metadata(&request)
}
